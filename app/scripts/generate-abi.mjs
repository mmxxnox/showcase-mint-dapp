// Copies the compiled ABIs into typed `as const` modules so wagmi/viem infer argument and return types.
// Run `npx hardhat build` in the parent folder first, then `npm run abi` here.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifacts = join(here, "..", "..", "artifacts", "contracts");
const out = join(here, "..", "src", "abi");
mkdirSync(out, { recursive: true });

for (const [name, file] of [
  ["ShowcaseNFT", "showcaseNftAbi"],
  ["ShowcaseToken", "showcaseTokenAbi"],
]) {
  const { abi } = JSON.parse(readFileSync(join(artifacts, `${name}.sol`, `${name}.json`), "utf8"));
  const body = `// Generated by scripts/generate-abi.mjs from the ${name} artifact. Do not edit by hand.\nexport const ${file} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(out, `${file}.ts`), body);
  console.log(`wrote src/abi/${file}.ts (${abi.length} entries)`);
}
